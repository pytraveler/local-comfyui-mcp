#!/usr/bin/env bash
set -euo pipefail

G='\033[0;32m'
Y='\033[1;33m'
NC='\033[0m'

printf '%b\n' "${G} ==================================================${NC}"
printf '%b\n' "${Y}"
cat <<'EOF'
             _                       _
 _ __  _   _| |_ _ __ __ ___   _____| | ___ _ __
| '_ \| | | | __| '__/ _` \ \ / / _ \ |/ _ \ '__|
| |_) | |_| | |_| | | (_| |\ V /  __/ |  __/ |
| .__/ \__, |\__|_|  \__,_| \_/ \___|_|\___|_|
|_|    |___/
EOF
if [ -n "${1:-}" ]; then
    echo
    echo "  $1"
fi
printf '%b\n' "${NC}${G} ==================================================${NC}"
echo
